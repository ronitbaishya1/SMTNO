#!/usr/bin/env python3
"""SMTNO Step 1D: generalized FEM eigenvalues and scale-filter spectral checks.

Install once if needed: python -m pip install numpy scipy pandas matplotlib

Save as:
  SMTNO/FEM/burgers_1d/run_step1d_eigenmodes.py
Run from any directory:
  python /path/to/SMTNO/FEM/burgers_1d/run_step1d_eigenmodes.py

Requires data generated by Step 1C:
  SMTNO/datasets/processed/burgers_1d/fine_filtered_and_stress.npz

This is a diagnostic spectral baseline, not a trained neural operator,
and not the eigenproblem of the nonlinear effective closure.
"""
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from scipy.linalg import eigh

PROJECT = Path(__file__).resolve().parents[2]
INPUT = PROJECT / 'datasets' / 'processed' / 'burgers_1d' / 'fine_filtered_and_stress.npz'
OUT = PROJECT / 'results' / 'burgers_1d' / 'step1D'
OUT.mkdir(parents=True, exist_ok=True)

NU = 0.02
MESH_SIZES = (64, 128)
MAX_K = 12
ELL_VALUES = (0.01, 0.02, 0.04)


def fem_matrices(n):
    """Periodic P1 FEM mass/stiffness for -d²/dx² on [0, 1]."""
    h = 1.0 / n
    M = np.eye(n) * (2.0*h/3.0)
    K = np.eye(n) * (2.0/h)
    for i in range(n):
        j = (i + 1) % n
        M[i, j] += h/6.0
        M[j, i] += h/6.0
        K[i, j] += -1.0/h
        K[j, i] += -1.0/h
    return M, K


def gaussian_filter_periodic(u, ell):
    n = u.shape[-1]
    k = 2.0*np.pi*np.fft.rfftfreq(n, d=1.0/n)
    return np.fft.irfft(np.fft.rfft(u, axis=-1)*np.exp(-0.5*(ell*k)**2), n=n, axis=-1)


def save_workflow():
    labels = [
        'Step 1C:\nFiltered FEM states',
        'Assemble P1 FEM\nmass M and stiffness K',
        'Solve K phi = lambda M phi\n(on each numerical mesh)',
        'Check mode decay and\nGaussian filter attenuation',
        'Test Gaussian\nscale composition',
        'Next: coarse evolution\nand learned closure'
    ]
    fig, ax = plt.subplots(figsize=(13, 4.2))
    ax.set_xlim(0,1)
    ax.set_ylim(0,1)
    ax.axis('off')
    ax.set_title('SMTNO Step 1D: FEM eigenvalue and physical-scale diagnostics', pad=24)
    xpos = np.linspace(0.11, 0.89, len(labels))
    for i, (x, label) in enumerate(zip(xpos, labels)):
        ax.text(x, 0.54, label, ha='center', va='center', fontsize=8,
                bbox=dict(boxstyle='round,pad=0.55', facecolor='white', edgecolor='black'))
        if i < len(labels)-1:
            ax.annotate('', xy=(xpos[i+1]-0.071,0.54), xytext=(x+0.071,0.54),
                        arrowprops=dict(arrowstyle='->',lw=1.5))
    fig.savefig(OUT/'step1D_workflow.png',dpi=180,bbox_inches='tight')
    plt.close(fig)


def main():
    if not INPUT.is_file():
        raise FileNotFoundError(
            'Missing Step 1C dataset: ' + str(INPUT) + '\n'
            'Run run_step1c_filtering.py before this script.'
        )
    with np.load(INPUT) as data:
        times = data['times'].astype(float)
        x = data['x'].astype(float)
        fine = data['fine_states'].astype(float)
        widths = data['ell'].astype(float)
        filtered = data['filtered_states'].astype(float)
    if fine.ndim != 2 or len(times) != len(fine) or len(x) != fine.shape[1]:
        raise ValueError('Unexpected Step 1C trajectory shape')
    if not (np.allclose(x, np.arange(len(x))/len(x))):
        raise ValueError('Step 1D assumes uniform periodic sampling on [0,1)')

    print(f'Step 1D: {len(times)} snapshots, {len(x)} periodic sample points')
    print('Building discrete periodic P1 mass and stiffness matrices')
    eigen_rows=[]
    eigen_errors={}
    for n in MESH_SIZES:
        M,K=fem_matrices(n)
        eigvals,eigvecs=eigh(K,M,check_finite=True)
        # Eigenvectors from eigh are normalized as v^T M v = 1.
        residual=np.linalg.norm(K@eigvecs[:,:2*MAX_K+1]-(M@eigvecs[:,:2*MAX_K+1])*eigvals[:2*MAX_K+1],axis=0)
        max_eig_residual=float(np.max(residual))
        if max_eig_residual>1e-6:
            raise RuntimeError(f'Unexpected FEM eigen residual N={n}: {max_eig_residual}')
        for k in range(1,MAX_K+1):
            # Periodic modes k and -k have equal eigenvalues (two-dimensional eigenspace).
            j1, j2=2*k-1, 2*k
            lam=float((eigvals[j1]+eigvals[j2])/2)
            continuous=float((2*np.pi*k)**2)
            eigen_rows.append({
                'N_elements':n,'mode_k':k,
                'eigenvalue_FEM':lam,
                'eigenvalue_continuum':continuous,
                'relative_eigenvalue_error':abs(lam-continuous)/continuous,
                'diffusion_decay_rate_nu_lambda':NU*lam,
                'modal_decay_time_1_over_nu_lambda':1.0/(NU*lam),
                'pair_split_abs':abs(float(eigvals[j2]-eigvals[j1])),
                'max_eigenpair_residual':max_eig_residual,
            })
        eigen_errors[n] = max_eig_residual
    eig_df = pd.DataFrame(eigen_rows)
    eig_df.to_csv(OUT/'fem_eigenvalues.csv', index=False)

    fig,ax=plt.subplots(figsize=(8,5))
    ks=np.arange(1,MAX_K+1)
    ax.plot(ks,(2*np.pi*ks)**2,label='Continuum Laplacian: (2 pi k)^2',lw=2)
    for n in MESH_SIZES:
        part=eig_df[eig_df.N_elements==n].sort_values('mode_k')
        ax.plot(part.mode_k, part.eigenvalue_FEM,'o--',ms=4,label=f'Periodic P1 FEM, N={n}')
    ax.set(xlabel='Fourier mode number k',ylabel='Eigenvalue lambda_k',title='Periodic FEM generalized eigenvalues')
    ax.legend(); ax.grid(alpha=.2); fig.tight_layout()
    fig.savefig(OUT/'fem_eigenvalue_comparison.png',dpi=180);plt.close(fig)

    fig,ax=plt.subplots(figsize=(8,5))
    for n in MESH_SIZES:
        part=eig_df[eig_df.N_elements==n].sort_values('mode_k')
        ax.semilogy(part.mode_k, part.relative_eigenvalue_error, 'o-',label=f'N={n}')
    ax.set(xlabel='Fourier mode number k',ylabel='Relative eigenvalue error',
           title='FEM spectral discretization error')
    ax.legend();ax.grid(alpha=.2);fig.tight_layout()
    fig.savefig(OUT/'fem_eigenvalue_error.png',dpi=180);plt.close(fig)

    # Exact semigroup composition for Gaussian filter with standard deviation ell:
    # P_ell2 == P_sqrt(ell2^2-ell1^2) o P_ell1, if ell2 >= ell1.
    semigroup_rows=[]
    for ell1,ell2 in [(0.01,0.02),(0.02,0.04),(0.01,0.04)]:
        for i in (0, len(times)//2, len(times)-1):
            u=fine[i]
            direct=gaussian_filter_periodic(u,ell2)
            sequential=gaussian_filter_periodic(
                gaussian_filter_periodic(u,ell1),np.sqrt(ell2**2-ell1**2))
            err=float(np.linalg.norm(sequential-direct)/(np.linalg.norm(direct)+1e-15))
            semigroup_rows.append({
                'time':times[i], 'ell1':ell1,'ell2':ell2,
                'incremental_gaussian_width':float(np.sqrt(ell2**2-ell1**2)),
                'relative_scale_composition_error':err
            })
    scale_df=pd.DataFrame(semigroup_rows)
    scale_df.to_csv(OUT/'gaussian_scale_composition.csv',index=False)

    # Verify the saved filtering (obtained in Step 1C) against independent computation.
    saved_filter_errors=[]
    for j,ell in enumerate(widths):
        calc=gaussian_filter_periodic(fine, float(ell))
        saved_filter_errors.append(float(np.linalg.norm(calc-filtered[:,j])/(np.linalg.norm(calc)+1e-15)))
    if max(saved_filter_errors)>1e-10:
        raise RuntimeError('Step 1C stored filters do not match expected Gaussian filters')

    # Compare Gaussian *physical* attenuation and viscous *temporal* modal decay.
    fig,ax=plt.subplots(figsize=(8.3,5.1))
    k=np.arange(0,35)
    for ell in ELL_VALUES:
        atten=np.exp(-0.5*(ell*2*np.pi*k)**2)
        ax.plot(k,atten,label=f'Gaussian physical width ell={ell:g}')
    ax.set(xlabel='Fourier mode number k', ylabel='Amplitude retained by filter',
           title='Physical filtering removes high modes at increasing scale')
    ax.legend();ax.grid(alpha=.2);fig.tight_layout()
    fig.savefig(OUT/'gaussian_mode_attenuation.png',dpi=180);plt.close(fig)

    fig,ax=plt.subplots(figsize=(8.3,5.1))
    kpos=np.arange(1,25)
    for t in (0.02,0.10,0.20):
        ax.plot(kpos,np.exp(-NU*(2*np.pi*kpos)**2*t),label=f'Pure diffusion at t={t:g}')
    ax.set(xlabel='Fourier mode number k',ylabel='Amplitude remaining',
           title='Viscous decay reference (diffusion alone; no nonlinear transfer)')
    ax.legend();ax.grid(alpha=.2);fig.tight_layout()
    fig.savefig(OUT/'diffusion_modal_decay.png',dpi=180);plt.close(fig)

    # Spectral modal comparison from nonlinear trajectory.
    fig,ax=plt.subplots(figsize=(8.3,5.1))
    freq=np.fft.rfftfreq(len(x), d=1/len(x))
    kmax=35
    for it,label in [(0,'Initial nonlinear Burgers state'),(-1,'Final nonlinear Burgers state')]:
        amp=np.abs(np.fft.rfft(fine[it]))/len(x)
        ax.semilogy(freq[1:kmax+1],np.maximum(amp[1:kmax+1],1e-15),'.-',label=label)
    ax.set(xlabel='Fourier mode number k',ylabel='Fourier amplitude (log scale)',
           title='Nonlinear Burgers changes spectral content over time')
    ax.legend();ax.grid(alpha=.2);fig.tight_layout()
    fig.savefig(OUT/'nonlinear_burgers_modal_spectrum.png',dpi=180);plt.close(fig)

    save_workflow()
    print('\nFirst 6 generalized eigenvalues (positive wave-number pairs):')
    print(eig_df[eig_df.N_elements==MESH_SIZES[-1]][['mode_k','eigenvalue_FEM','eigenvalue_continuum','relative_eigenvalue_error']].head(6).to_string(index=False))
    print(f'\nMax Gaussian composition error: {scale_df.relative_scale_composition_error.max():.2e}')
    print(f'Max saved Step 1C Gaussian recheck error: {max(saved_filter_errors):.2e}')
    print(f'All results saved to {OUT}')
    print('IMPORTANT: these eigenvalues are for the symmetric spatial Laplacian;')
    print('they are NOT the eigenvalues of the nonlinear coarse-grained evolution or its memory kernel.')


if __name__=='__main__':
    main()
